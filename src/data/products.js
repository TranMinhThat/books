// Helper function để lấy sản phẩm theo ID
export const getProductById = (id) => {
  return products.find(product => product.id === parseInt(id))
}

// Helper function để lấy sản phẩm liên quan
export const getRelatedProducts = (currentId, limit = 6) => {
  return products
    .filter(product => product.id !== parseInt(currentId))
    .slice(0, limit)
}

